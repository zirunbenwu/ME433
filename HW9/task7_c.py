def load_csv(path):
    t, y = [], []
    with open(path, 'r') as f:
        for row in csv.reader(f):
            if not row:
                continue
            try:
                t.append(float(row[0]))
                y.append(float(row[1]))
            except ValueError:
                continue   # skip header
    return np.array(t), np.array(y)

def fir_filter(data, h):
    # y[i] = sum_k h[k] * x[i-k]
    # Treat samples before i=0 as zero.
    N = len(h)
    out = np.zeros(len(data))
    for i in range(len(data)):
        s = 0.0
        for k in range(N):
            if i - k >= 0:
                s += h[k] * data[i - k]
        out[i] = s
    return out

def fft_one_sided(y, Fs):
    n = len(y)
    k = np.arange(n)
    T = n / Fs
    frq = k / T
    frq = frq[range(int(n/2))]
    Y = np.fft.fft(y) / n
    Y = Y[range(int(n/2))]
    return frq, Y

for name, cfg in filters.items():
    t, data = load_csv(f'{name}.csv')
    Fs = len(t) / t[-1]

    h = np.array(cfg['h'])
    N = len(h)
    if N == 0:
        print(f'{name}: no coefficients pasted yet, skipping')
        continue

    filtered = fir_filter(data, h)

    frq, Y_unf = fft_one_sided(data,     Fs)
    _,   Y_fil = fft_one_sided(filtered, Fs)

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 6))
    fig.suptitle(
        f"{name}  -  FIR low-pass sinc, {cfg['window']}, "
        f"N = {N}, fl = {cfg['fl']} Hz, bl = {cfg['bl']} Hz   "
        f"(Fs = {Fs:.1f} Hz)"
    )

    ax1.plot(t, data,     'k', linewidth=0.8, label='unfiltered')
    ax1.plot(t, filtered, 'r', linewidth=1.2, label='filtered')
    ax1.set_xlabel('Time (s)')
    ax1.set_ylabel('Amplitude')
    ax1.legend(loc='upper right')

    ax2.loglog(frq, abs(Y_unf), 'k', linewidth=0.8, label='unfiltered')
    ax2.loglog(frq, abs(Y_fil), 'r', linewidth=1.0, label='filtered')
    ax2.set_xlabel('Freq (Hz)')
    ax2.set_ylabel('|Y(freq)|')
    ax2.legend(loc='lower left')

    plt.tight_layout()

plt.show()